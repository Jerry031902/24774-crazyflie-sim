"""Reproduce the four-state ZOH/discrete LQR and generate firmware constants.

No scipy/control-toolbox dependency: exact analytical ZOH and DARE iteration.
This design assumes equal world-x/y drag and equal axis weights.
"""
import argparse
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]

def design(beta=0.5, ts=0.01, q_position=20., q_velocity=4., r_angle=300.):
    values = (beta, ts, q_position, q_velocity, r_angle)
    if not all(np.isfinite(values)) or beta < 0 or min(values[1:]) <= 0:
        raise ValueError("Finite nonnegative beta and positive sampling time/weights required")
    g = 9.81
    a = np.exp(-beta * ts)
    f = -np.expm1(-beta * ts) / beta if beta else ts
    h = (ts - f) / beta if beta else ts * ts / 2
    ad = np.eye(4)
    ad[0, 2] = ad[1, 3] = f
    ad[2, 2] = ad[3, 3] = a
    bd = np.array([[0, -g*h], [-g*h, 0], [0, -g*f], [-g*f, 0]])
    q, r = np.diag([q_position]*2 + [q_velocity]*2), np.eye(2)*r_angle
    p = q.copy()
    for _ in range(100000):
        k = np.linalg.solve(r + bd.T @ p @ bd, bd.T @ p @ ad)
        new = q + ad.T @ p @ ad - ad.T @ p @ bd @ k
        new = (new + new.T)/2
        if np.max(np.abs(new-p)) < 1e-11:
            p = new
            break
        p = new
    else:
        raise RuntimeError("DARE did not converge")
    k = np.linalg.solve(r+bd.T@p@bd, bd.T@p@ad)
    residual = np.max(np.abs(q+ad.T@p@ad-ad.T@p@bd@k-p))
    poles = np.linalg.eigvals(ad-bd@k)
    if np.max(np.abs(poles)) >= 1 or residual > 1e-7:
        raise RuntimeError("Unstable or inaccurate Riccati solution")
    return dict(beta=beta, ts_s=ts, gravity_m_s2=g, Q=q.tolist(), R=r.tolist(),
                Ad=ad.tolist(), Bd=bd.tolist(), K=k.tolist(),
                kp_angle_per_m=float(-k[0, 1]), kv_angle_per_m_s=float(-k[0, 3]),
                dare_residual=float(residual), spectral_radius=float(max(abs(poles))),
                assumptions="isotropic linear drag; small tilt; fast attitude loop; provisional parameters")

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--beta", type=float, default=.5)
    p.add_argument("--q-position", type=float, default=20.)
    p.add_argument("--q-velocity", type=float, default=4.)
    p.add_argument("--r-angle", type=float, default=300.)
    p.add_argument("--write-header", action="store_true")
    p.add_argument("--output", type=Path, default=ROOT/"build/lqr/design.json")
    args = p.parse_args()
    result = design(args.beta, q_position=args.q_position,
                    q_velocity=args.q_velocity, r_angle=args.r_angle)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2)+"\n", encoding="utf-8")
    if args.write_header:
        path = ROOT/"src/modules/interface/controller/horizontal_lqr_gains.h"
        path.write_text(
            "// Generated by sim/lqr/design.py; drag is ASSUMED, not measured.\n"
            "#ifndef HORIZONTAL_LQR_GAINS_H\n#define HORIZONTAL_LQR_GAINS_H\n"
            f"#define LQR_G 9.81f\n#define LQR_BETA {args.beta:.9e}f\n"
            f"#define LQR_KP {result['kp_angle_per_m']:.9e}f\n"
            f"#define LQR_KV {result['kv_angle_per_m_s']:.9e}f\n"
            "#define LQR_ANGLE_LIMIT_DEG 10.0f\n#endif\n", encoding="utf-8")
    print(json.dumps(result, indent=2))

if __name__ == "__main__":
    main()

